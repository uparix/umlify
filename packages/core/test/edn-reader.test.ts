import { describe, expect, it } from "vitest";
import { EDNReadError, readAllEDN, readEDN } from "../src/edn/reader";
import { Char, EDNMap, EDNSet, Sym, Tagged, ednEquals, get, items, keywordName, kw, name, type EDN } from "../src/edn/value";

// Port of umlviewer's EDNReaderTests.
const same = (text: string, expected: EDN) => expect(ednEquals(readEDN(text), expected)).toBe(true);
const map = (...pairs: [EDN, EDN][]) => new EDNMap(pairs);

describe("EDN reader", () => {
  it("reads scalars", () => {
    expect(readEDN("nil")).toBe(null);
    expect(readEDN("true")).toBe(true);
    expect(readEDN("false")).toBe(false);
    expect(readEDN("42")).toBe(42);
    expect(readEDN("-7")).toBe(-7);
    expect(readEDN("+7")).toBe(7);
    expect(readEDN("2.5")).toBe(2.5);
    expect(readEDN("1.0E-4")).toBe(0.0001);
    expect(readEDN("1e+16")).toBe(1e16);
    expect(readEDN('"hi"')).toBe("hi");
    expect(readEDN(":engine.layout")).toBe(kw("engine.layout"));
    expect(readEDN(":a/b")).toBe(kw("a/b"));
    expect(readEDN("defn-")).toBe(Sym.of("defn-"));
    expect(readEDN("-")).toBe(Sym.of("-"));
    expect(readEDN("->x")).toBe(Sym.of("->x"));
  });

  it("reads number suffixes and ratios", () => {
    expect(readEDN("12N")).toBe(12);
    expect(readEDN("1.5M")).toBe(1.5);
    expect(readEDN("1/4")).toBe(0.25);
    expect(readEDN("99999999999999999999")).toBe(1e20);
  });

  it("reads symbolic values", () => {
    expect(readEDN("##Inf")).toBe(Infinity);
    expect(readEDN("##-Inf")).toBe(-Infinity);
    expect(readEDN("##NaN")).toBeNaN();
  });

  it("reads strings", () => {
    expect(readEDN(String.raw`"a\"b\\c\nd\te"`)).toBe('a"b\\c\nd\te');
    expect(readEDN('"\\u00e9"')).toBe("é");
    expect(readEDN('"μ σ"')).toBe("μ σ");
  });

  it("reads characters", () => {
    same("\\a", new Char("a"));
    same("\\newline", new Char("\n"));
    same("\\space", new Char(" "));
    same("\\u0041", new Char("A"));
    same("\\μ", new Char("μ"));
    same("[\\( \\)]", [new Char("("), new Char(")")]);
  });

  it("reads collections", () => {
    same("[1 2 3]", [1, 2, 3]);
    same("(1, 2)", [1, 2]);
    same("{:a 1, :b [2]}", map([kw("a"), 1], [kw("b"), [2]]));
    same("#{:x :y}", new EDNSet([kw("x"), kw("y")]));
    const m = readEDN("{[:engine.compose :engine.layout] :association}") as EDNMap;
    expect(m.get([kw("engine.compose"), kw("engine.layout")])).toBe(kw("association"));
    same("[]", []);
    same("{}", new EDNMap());
  });

  it("skips comments and discarded forms", () => {
    const text = [
      ";; Generated by clj -M:ir from the policy file. Do not edit.",
      "{:a 1 ; trailing",
      " #_ :gone #_ #_ 1 2",
      " :b [#_x 2]}",
    ].join("\n");
    same(text, map([kw("a"), 1], [kw("b"), [2]]));
  });

  it("reads tags", () => {
    same('#inst "2026-10-24"', new Tagged("inst", "2026-10-24"));
    same("#my/point [1 2]", new Tagged("my/point", [1, 2]));
  });

  it("keeps file order in maps and sets", () => {
    const m = readEDN("{:z 1 :a 2 :m 3 :b 4 :y 5 :c 6 :x 7 :d 8 :w 9}") as EDNMap;
    expect(m.keys().map(keywordName)).toEqual(["z", "a", "m", "b", "y", "c", "x", "d", "w"]);
    expect(items(readEDN("#{:z :a :m :b}"))?.map(keywordName)).toEqual(["z", "a", "m", "b"]);
  });

  it("follows Clojure equality", () => {
    expect(ednEquals(readEDN("{:a 1 :b 2}"), readEDN("{:b 2 :a 1}"))).toBe(true);
    expect(ednEquals(readEDN("#{1 2}"), readEDN("#{2 1}"))).toBe(true);
    expect(ednEquals(kw("a"), Sym.of("a"))).toBe(false);
    expect(ednEquals(kw("a"), "a")).toBe(false);
  });

  it("has lenient accessors", () => {
    const v = readEDN('{:id :engine.layout :w 120 :ok nil :name "Layout" :tags #{:a}}');
    expect(keywordName(get(v, "id"))).toBe("engine.layout");
    expect(name(kw("a/b"))).toBe("b");
    expect(get(v, "w")).toBe(120);
    expect(get(v, "ok")).toBe(null);
    expect(get(v, "missing")).toBeUndefined();
    expect(items(get(v, "tags"))).toEqual([kw("a")]);
  });

  it.each([
    ["[1 2", "missing ']'", 1, 5],
    ["{:a}", "map needs an even number of forms", 1, 5],
    ["{:a 1 :a 2}", "duplicate map key :a", 1, 12],
    ["#{1 1}", "duplicate set element 1", 1, 7],
    ["]", "unmatched ']'", 1, 1],
    ['"abc', "missing closing '\"'", 1, 5],
    ["[1]\n 2", "more than one form", 2, 3],
    ["", "no form", 1, 1],
    ["##Foo", "unknown symbolic value ##Foo", 1, 6],
    ["1.2.3", "bad number '1.2.3'", 1, 6],
    ["1/2N", "bad number '1/2N'", 1, 5],
  ])("reports %j as %s at %i:%i", (text, reason, line, column) => {
    expect(() => readEDN(text)).toThrow(new EDNReadError(reason, line, column));
    try {
      readEDN(text);
    } catch (e) {
      expect(e).toMatchObject({ reason, line, column });
    }
  });

  it("reads all forms", () => {
    expect(ednEquals(readAllEDN("1 :a ; c\n [2]"), [1, kw("a"), [2]])).toBe(true);
    expect(readAllEDN("  ; only a comment\n")).toEqual([]);
  });
});
